import type { Action, Card, CardNode } from "@/schema/card"

export type HandledAction = { id: string; type: Action["type"]; label: string }
export type FormField = { name: string; kind: "string" | "bool"; required: boolean }

/** Every distinct button action and named field in the card, in document order. */
export function collectCardIO(card: Card): { actions: HandledAction[]; fields: FormField[] } {
  const actions = new Map<string, HandledAction>()
  const fields = new Map<string, FormField>()
  const walk = (nodes: CardNode[]) => {
    for (const node of nodes) {
      switch (node.type) {
        case "button":
          if (!actions.has(node.action.id)) {
            actions.set(node.action.id, { id: node.action.id, type: node.action.type, label: node.label })
          }
          break
        case "stack":
        case "actions":
          walk(node.children)
          break
        case "input":
        case "textarea":
        case "select":
        case "checkbox":
          fields.set(node.name, {
            name: node.name,
            kind: node.type === "checkbox" ? "bool" : "string",
            required: node.required ?? false,
          })
          break
      }
    }
  }
  walk(card.children)
  return { actions: [...actions.values()], fields: [...fields.values()] }
}

const goVar = (name: string) => {
  const v = name.replace(/[^A-Za-z0-9_]/g, "_").replace(/^(\d)/, "_$1")
  return ["type", "func", "var", "map", "range", "go", "case", "default", "select", "chan"].includes(v) ? `${v}Value` : v
}

const tsVar = (name: string) => {
  const v = name.replace(/[^A-Za-z0-9_$]/g, "_").replace(/^(\d)/, "_$1")
  return ["default", "case", "new", "delete", "function", "var", "class", "switch"].includes(v) ? `${v}Value` : v
}

/** A runnable `net/http` server that switches on this card's action ids. */
export function generateGoHandler(card: Card): string {
  const { actions, fields } = collectCardIO(card)
  const cases = actions.map((a) => {
    const lines = [`\tcase ${JSON.stringify(a.id)}: // ${a.type} · ${JSON.stringify(a.label)}`]
    if (a.type === "submit" && fields.length > 0) {
      for (const f of fields) {
        lines.push(`\t\t${goVar(f.name)}, _ := event.FormValues[${JSON.stringify(f.name)}].(${f.kind})`)
      }
      for (const f of fields.filter((f) => f.required)) {
        const empty = f.kind === "bool" ? `!${goVar(f.name)}` : `${goVar(f.name)} == ""`
        lines.push(`\t\tif ${empty} { // the client checks this too, but never trust it`)
        lines.push(`\t\t\thttp.Error(w, ${JSON.stringify(`${f.name} is required`)}, http.StatusUnprocessableEntity)`)
        lines.push(`\t\t\treturn`)
        lines.push(`\t\t}`)
      }
      const format = fields.map((f) => `${f.name}=${f.kind === "bool" ? "%v" : "%q"}`).join(" ")
      lines.push(`\t\tlog.Printf("${a.id}: ${format}", ${fields.map((f) => goVar(f.name)).join(", ")})`)
    } else {
      lines.push(`\t\tlog.Printf("${a.id}: payload=%v", event.Payload)`)
    }
    return lines.join("\n")
  })

  return `// Sample backend for card ${JSON.stringify(card.id ?? "(no id)")}, generated by Card Playground.
// Run with: go run handler.go

package main

import (
\t"encoding/json"
\t"log"
\t"net/http"
)

// ActionEvent is what the chat client POSTs when a card button is pressed.
type ActionEvent struct {
\tCardID     string         \`json:"cardId,omitempty"\`
\tActionID   string         \`json:"actionId"\`
\tType       string         \`json:"type"\`
\tURL        string         \`json:"url,omitempty"\`
\tPayload    map[string]any \`json:"payload,omitempty"\`
\tFormValues map[string]any \`json:"formValues,omitempty"\`
\tTimestamp  string         \`json:"timestamp"\`
}

func handleCardAction(w http.ResponseWriter, r *http.Request) {
\tvar event ActionEvent
\tif err := json.NewDecoder(r.Body).Decode(&event); err != nil {
\t\thttp.Error(w, "invalid event", http.StatusBadRequest)
\t\treturn
\t}

\tswitch event.ActionID {
${cases.join("\n")}
\tdefault:
\t\thttp.Error(w, "unknown action", http.StatusBadRequest)
\t\treturn
\t}
\tw.WriteHeader(http.StatusNoContent)
}

func main() {
\thttp.HandleFunc("POST /card-actions", handleCardAction)
\tlog.Println("listening on :8080")
\tlog.Fatal(http.ListenAndServe(":8080", nil))
}
`
}

/** An Express server that switches on this card's action ids. */
export function generateTsHandler(card: Card): string {
  const { actions, fields } = collectCardIO(card)
  const cases = actions.map((a) => {
    const lines = [`    case ${JSON.stringify(a.id)}: { // ${a.type} · ${JSON.stringify(a.label)}`]
    if (a.type === "submit" && fields.length > 0) {
      for (const f of fields) {
        const read = `event.formValues?.[${JSON.stringify(f.name)}]`
        lines.push(`      const ${tsVar(f.name)} = ${f.kind === "bool" ? `${read} === true` : `String(${read} ?? "")`}`)
      }
      for (const f of fields.filter((f) => f.required)) {
        const empty = f.kind === "bool" ? `!${tsVar(f.name)}` : `${tsVar(f.name)} === ""`
        lines.push(`      // The client checks this too, but never trust it.`)
        lines.push(`      if (${empty}) return res.status(422).json({ error: ${JSON.stringify(`${f.name} is required`)} })`)
      }
      lines.push(`      console.log(${JSON.stringify(a.id)}, { ${fields.map((f) => tsVar(f.name)).join(", ")} })`)
    } else {
      lines.push(`      console.log(${JSON.stringify(a.id)}, event.payload)`)
    }
    lines.push(`      break`, `    }`)
    return lines.join("\n")
  })

  return `// Sample backend for card ${JSON.stringify(card.id ?? "(no id)")}, generated by Card Playground.
// Run with: npm i express && npx tsx handler.ts

import express from "express"

/** What the chat client POSTs when a card button is pressed. */
type ActionEvent = {
  cardId?: string
  actionId: string
  type: "submit" | "postback" | "openUrl"
  url?: string
  payload?: Record<string, unknown>
  formValues?: Record<string, string | boolean>
  timestamp: string
}

const app = express()
app.use(express.json())

app.post("/card-actions", (req, res) => {
  const event = req.body as ActionEvent
  switch (event.actionId) {
${cases.join("\n")}
    default:
      return res.status(400).json({ error: "unknown action" })
  }
  res.sendStatus(204)
})

app.listen(8080, () => console.log("listening on :8080"))
`
}
