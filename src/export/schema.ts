import { defs, type JsonSchema } from "@/docs/props"

export { defs, type JsonSchema }

export const refName = (ref: string) => ref.split("/").pop()!

/** Node definitions in schema order, e.g. ["HeaderNode", "TextNode", …]. */
export const nodeDefNames = (defs.Node.oneOf ?? []).map((s) => refName(s.$ref!))

export const actionVariants = defs.Action.oneOf ?? []

/** Merge the Action variants into one property list; a field is required only if every variant requires it. */
export function mergedActionProps(): { name: string; schema: JsonSchema; required: boolean }[] {
  const out = new Map<string, { name: string; schema: JsonSchema; required: boolean }>()
  for (const v of actionVariants) {
    for (const [name, schema] of Object.entries(v.properties ?? {})) {
      const required = actionVariants.every((o) => o.required?.includes(name))
      if (!out.has(name)) out.set(name, { name, schema, required })
    }
  }
  return [...out.values()]
}

export const actionTypes = actionVariants.map((v) => String(v.properties!.type.const))

